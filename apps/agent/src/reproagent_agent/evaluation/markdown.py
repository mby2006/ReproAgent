def _source_label(source, human_confirmed: bool = False) -> str:
    return _SOURCE_LABELS.get(
        source, "unknown（旧记录已确认，来源未知）" if human_confirmed else "未确认"
    )


def _event_value(value: object) -> str:
    return json.dumps(value, ensure_ascii=False, sort_keys=True, default=str)


def _cell(value: object) -> str:
    if value is None:
        return "—"
    return str(value).replace("|", "\\|").replace("\n", " ")


def _table(headers: list[str], rows: list[list[object]]) -> str:
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join(["---"] * len(headers)) + "|"]
    for row in rows:
        lines.append("| " + " | ".join(_cell(v) for v in row) + " |")
    return "\n".join(lines)


def _fmt(value: float | None, digits: int = 4) -> str:
    return "—" if value is None else f"{value:.{digits}f}"


def _metric(value: float | None, unit: str | None) -> str:
    """Render a metric the way a reader expects to see it (percent for fractions)."""
    if value is None:
        return "—"
    if unit == "fraction":
        return f"{value * 100:.2f}%"
    if unit == "seconds":
        return f"{value:.1f} 秒"
    return f"{_fmt(value)} {unit or ''}".strip()


def _gap(comparison: MetricComparison) -> str:
    if comparison.percentage_point_difference is not None:
        return f"{comparison.percentage_point_difference:+.2f} 个百分点"
    return _metric(comparison.absolute_difference, comparison.unit)


_MISSING_GLOSS: list[tuple[str, str]] = [
    ("weight init", "论文没说参数一开始取什么值，不同取法会影响训练收敛快慢。"),
    ("regulariz", "论文没说用什么手段防止模型死记训练数据（过拟合）。"),
    ("training sample", "论文没说每个实验具体用了多少样本。"),
    ("language model", "论文提到的 GTN 里用了什么语言模型，没有给出细节。"),
    ("oversegmentation", "把一整行字切成单个字符的具体规则没写清楚。"),
    ("computational cost", "论文没有给出训练这套模型需要多少算力。"),
    ("data augmentation", "论文没说训练时对图片做了哪些变形、扩充。"),
    ("preprocessing", "图片怎么归一化、怎么对齐，论文写得不够具体。"),
]


def _missing_gloss(raw: str) -> str:
    haystack = raw.lower()
    for keyword, gloss in _MISSING_GLOSS:
        if keyword in haystack:
            return gloss
    return "论文没有给出这一项的具体做法，复现时只能按常规做法补齐。"


def _missing_text(raw: str) -> str:
    """Turn internal references like ``方法验证/layer_configuration`` into prose."""
    if "/" not in raw:
        return raw
    scope, _, detail = raw.partition("/")
    head, _, tail = detail.partition("：")
    label = _ITEM_LABELS.get(head, head)
    note = f"（{tail}）" if tail else ""
    if scope == "方法验证":
        return f"代码实现中的「{label}」无法与论文比对{note}"
    if scope == "实验验证":
        return f"实际运行中的「{label}」无法与计划比对{note}"
    if scope == "结果对比":
        return f"「{label}」论文未报告{note}"
    return raw


def _is_random_guess(request: EvaluateRequest, comparison) -> bool:
    """Describe an observed accuracy within three points of uniform guessing."""
    if comparison is None or comparison.metric != "accuracy" or comparison.unit != "fraction":
        return False
    if comparison.experiment_value is None:
        return False
    classes = request.plan.dataset_config.num_classes
    if not classes or classes < 2:
        return False
    return abs(comparison.experiment_value - 1 / classes) <= 0.03


def reader_summary(request: EvaluateRequest, report: EvaluationReport) -> str:
    if report.final_status is FinalStatus.EXECUTION_FAILED:
        return "这次实验没有顺利完成，还没有可以用来核对论文结论的完整测试成绩。"
    correct = request.metrics.get("correct_count")
    total = request.metrics.get("evaluated_count")
    lines = []
    if type(correct) is int and type(total) is int and 0 <= correct <= total and total > 0:
        lines.append(
            f"模型做了 {total:,} 道识别题，答对 {correct:,} 道，答错 {total - correct:,} 道。"
        )
    target = next((c for c in report.metric_comparisons if c.metric == report.target_metric), None)
    if target and target.metric in {"accuracy", "error_rate"} and target.unit == "fraction":
        action = "答对" if target.metric == "accuracy" else "答错"
        if target.experiment_value is not None:
            lines.append(
                f"按每 100 道题折算，本次平均{action} {100 * target.experiment_value:.1f} 道。"
            )
        if target.paper_value is not None:
            lines.append(
                f"按同一指标折算，论文平均每 100 道{action} {100 * target.paper_value:.1f} 道。"
            )
    elif target and target.metric == "test_loss" and target.experiment_value is not None:
        lines.append(
            f"本次给预测错误程度打出的平均分是 {_metric(target.experiment_value, target.unit)}。"
            "评分规则相同时，分数越低越好。"
        )
    interpretations = {
        FinalStatus.DEVIATION_FOUND: (
            "核对时发现，代码与论文的做法或实际运行与计划之间有出入。请在条件表中查看具体差别。"
        ),
        FinalStatus.INSUFFICIENT_EVIDENCE: (
            "还有关键设置或成绩缺少证据，现有记录不足以判断两次实验是否吻合。"
        ),
        FinalStatus.METHOD_VALIDATED: (
            "已核对的关键做法与论文相符，主要成绩也落在计划允许的差距内。"
            "这个判断只适用于本次缩小规模的实验。"
        ),
        FinalStatus.SCALED_RUN_COMPLETED: (
            "小规模实验跑完了，主要成绩与论文的差距超过计划允许的范围。单次比较无法定位原因。"
        ),
        FinalStatus.PARTIAL_MATCH: (
            "有些成绩接近论文，有些超出了计划允许的差距。需要分别查看各项成绩。"
        ),
    }
    lines.append(interpretations[report.final_status])
    return "".join(lines)


def _what_it_answers(request: EvaluateRequest, report: EvaluationReport, comparison):
    can, cannot = [], []
    can.append("我们的实现是否真的跑通了（代码、配置、环境全部可追溯）。")
    can.append("在缩小规模的前提下，得到的结果与论文差多少。")
    can.append("论文哪些关键设置没有写清楚，需要人为假设。")
    cannot.append("不能证明论文结论正确或错误——单个缩小规模的实验做不到这一点。")
    if report.review_mode is not None and report.review_mode.value == "delegated":
        cannot.append("不能当作“已人工认定正确”的结果——本次关键假设由系统自动接受。")
    if _is_random_guess(request, comparison):
        cannot.append("仅凭一次接近猜测基线的准确率，无法判断训练中参数是否更新。")
    return can, cannot


def render_markdown(
    request: EvaluateRequest, report: EvaluationReport, facts: ImplementationFacts
) -> str:
    card = request.card
    plan = request.plan
    refs = report.references
    sections: list[str] = []

    title = request.paper_title or str(card.method.value or "未命名论文")
    ev = plan.evaluation_config
    wanted = report.target_metric or execution_metric(ev.target_metric) or ev.target_metric
    comparison = next((c for c in report.metric_comparisons if c.metric == wanted), None)
    status = report.final_status
    can, cannot = _what_it_answers(request, report, comparison)

    headline = [
        f"# 复现报告：{title}",
        "",
        report.reader_summary or reader_summary(request, report),
        "",
        f"> **结论：{_STATUS_LABELS[status]}**",
    ]
    if comparison is not None:
        headline += [
            "",
            "> | 指标 | 论文报告 | 本次实验 | 差距 |",
            "> |---|---|---|---|",
            f"> | {comparison.metric} | {_metric(comparison.paper_value, comparison.unit)} "
            f"| {_metric(comparison.experiment_value, comparison.unit)} "
            f"| {_gap(comparison)} |",
        ]
    headline += ["", "> **这份报告能回答**"]
    headline += [f"> - {line}" for line in can]
    headline += ["", "> **这份报告不能回答**"]
    headline += [f"> - {line}" for line in cannot]
    counts = request.metrics
    if (
        counts.get("correct_count") is None
        and counts.get("target_metric") in {"error_rate", "error rate"}
    ):
        headline.append("旧版运行未记录正确样本数，原始目标值不可独立核验。")
    sections.append("\n".join(headline))

    mode = report.review_mode.value if report.review_mode else "unknown"
    sections.append(
        f"> **谁审核了这次实验**：{_REVIEW_LABELS.get(mode, '审核来源未知')}（{mode}）\n>\n"
        f"> {report.review_disclaimer or '缺少审核记录，不能认定已人工逐项核验。'}"
        + (
            f"\n>\n> 托管授权用户：`{report.delegated_by}`；"
            f"授权时间：{report.delegated_at.isoformat()}"
            if report.delegated_at and report.delegated_by else ""
        )
    )

    # --- 1. 目的 -------------------------------------------------------------
    reference = "缺少可核验的论文参考值。"
    if comparison and comparison.paper_value is not None and comparison.paper_evidence:
        evidence = comparison.paper_evidence
        page = f"（论文第 {evidence.source_page} 页）" if evidence.source_page else ""
        reference = (
            f"按该指标换算的论文参考值为 **{_metric(comparison.paper_value, comparison.unit)}**"
            f"{page}。"
        )
        if evidence.detail:
            reference += f"原文记录：{evidence.detail}。"
    purpose = [
        "## 1. 这次实验想验证什么",
        "",
        f"论文提出的方法是 **{card.method.value}**，模型是 **{card.model_architecture.value}**，"
        f"数据集是 **{card.dataset.value}**。"
        f"计划主指标为 `{ev.target_metric}`。{reference}",
        "",
        "本次没有照搬论文的原始训练条件，而是用**缩小规模**的方式跑一遍，"
        "目的是验证整条复现流程是否成立、结果与论文相差多少，而不是宣称完整复现。",
        "",
        f"- 缩放策略：`{plan.scaling_profile}`",
        f"- 计划说明：{plan.rationale}",
        f"- 允许的浮动范围（容差）：{ev.tolerance}。{ev.comparison_note}",
    ]
    actual_target = request.metrics.get("target_metric")
    recorded_target = execution_metric(actual_target) if isinstance(actual_target, str) else None
    if isinstance(actual_target, str) and (recorded_target or actual_target) != wanted:
        purpose.append(
            f"\n> 注意：计划记录的目标指标是 `{ev.target_metric}`，"
            f"运行记录的目标指标是 `{actual_target}`。报告仍按获批目标核查。"
        )
    if wanted == "error_rate":
        purpose.append("错误率 = 1 − 准确率。两种表示分别列出，主指标按错误率比较。")
    sections.append("\n".join(purpose))

    # --- 2. 流程 -------------------------------------------------------------
    evidence_fields = [
        ("方法", card.method),
        ("架构", card.model_architecture),
        ("优化器", card.optimizer),
        ("损失函数", card.loss_function),
        ("数据集", card.dataset),
        *[(f"超参 {name}", field) for name, field in card.hyperparameters.items()],
    ]
    backed = [
        name for name, field in evidence_fields
        if field.status.value in ("paper_explicit", "paper_described")
    ]
    process = [
        "## 2. 复现是怎么做的",
        "",
        "1. **读论文、抽信息**：把方法、架构、数据集、超参等关键信息抽出来，"
        "每一条都记录它在论文第几页、原句是什么。",
        f"   本次共抽出 {len(evidence_fields)} 项，其中 {len(backed)} 项能直接对到论文原文，"
        f"其余 {len(evidence_fields) - len(backed)} 项需要推断。",
        "2. **补齐论文没写清的部分**：论文常见“只给结论不给细节”，这些空缺会被标记为"
        "“假设”，由你逐项确认或由 AI 建议后采纳。",
        "3. **生成可运行的代码**：按确认过的配置生成训练脚本。代码由模板和配置生成，"
        "不让大模型自由编写，因此每次生成的代码都能对应到具体设置。",
        "4. **在隔离环境里真实训练**：容器内无网络、无密钥、非 root，"
        "数据集和执行镜像都记录指纹，确保结果可追溯。",
        "5. **拿真实训练日志对比论文数字**：所有实验数值来自本次运行的原始记录，"
        "不使用估计值，最后由规则引擎给出判定。",
    ]
    sections.append("\n".join(process))

    # --- 3. 设置对照 ---------------------------------------------------------
    setup_rows = []
    for row in report.parameter_comparisons:
        paper = row.paper_evidence
        actual = row.actual_evidence
        paper_details = [row.paper, paper.quote] if paper else []
        if paper and paper.source_page:
            paper_details.append(f"p.{paper.source_page}")
        actual_details = (
            [row.actual, actual.kind, actual.file_path, actual.field_path]
            if actual and row.actual is not None else []
        )
        setup_rows.append([
            row.label, " · ".join(filter(None, paper_details)) or "缺少原文证据",
            row.plan, " · ".join(filter(None, actual_details)) or "未核实",
            " · ".join(filter(None, [row.decision, row.note])),
        ])
    sections.append(
        "## 3. 论文怎么写的 vs 本次实际怎么跑\n\n"
        "运行指标和审计记录反映本次观测，固定配置和代码说明实现设置。\n\n"
        + _table(["项目", "论文与出处", "计划", "本次记录及来源", "决定与核查"], setup_rows)
    )

    # --- 4. 结果 -------------------------------------------------------------
    result_rows = [
        [
            c.metric,
            _metric(c.paper_value, c.unit),
            _metric(c.experiment_value, c.unit),
            _gap(c),
            _CHECK_PLAIN.get(c.comparison_status.value, c.comparison_status.value),
        ]
        for c in report.metric_comparisons
    ]
    reading = []
    if _is_random_guess(request, comparison):
        classes = plan.dataset_config.num_classes
        reading.append(
            f"**怎么读这张表**：{classes} 类分类任务随机猜对的概率是 {100 / classes:.2f}%，"
            f"本次跑出 {_metric(comparison.experiment_value, comparison.unit)}，"
            "与该基线接近。测试样本数和多次独立运行的波动会影响解读。"
        )
    elif comparison is not None and comparison.percentage_point_difference is not None:
        gap = comparison.percentage_point_difference
        reading.append(f"**怎么读这张表**：主指标的百分点差为 {gap:+.2f}，按本次值减去论文值计算。")
    reading.append(
        "表中“论文报告”一列来自论文原文（附页码证据），“本次实验”一列来自本次运行的真实日志，"
        "两者都不做估算或补全。"
    )
    sections.append(
        "## 4. 跑出了什么结果\n\n"
        + (_table(["指标", "论文报告", "本次实验", "差距", "是否吻合"], result_rows)
           if result_rows else "（本次运行没有产出可比对的指标）")
        + "\n\n"
        + "\n\n".join(reading)
    )

    # --- 5. 差异 -------------------------------------------------------------
    deviated_methods = [c for c in report.method_checks if c.status.value == "deviated"]
    unknown_methods = [c for c in report.method_checks if c.status.value == "unknown"]
    differences = ["## 5. 和论文不一样的地方", ""]
    differences.append("**一、计划相对论文的调整**")
    if plan.deviations_from_paper:
        differences += [
            f"- {_FIELD_LABELS.get(d.field_path.split('.')[-1], d.field_path)}："
            f"论文 {d.paper_value} → 计划 {d.plan_value}（{d.reason}）"
            for d in plan.deviations_from_paper
        ]
    else:
        differences.append("- 无")
    differences += ["", "**二、实现与论文不一致（需要重视）**"]
    if deviated_methods:
        differences += [
            f"- {_ITEM_LABELS.get(c.item.value, c.item.value)}："
            f"论文用「{c.paper_value}」，本次实现是「{c.implementation_value}」。{c.note}"
            for c in deviated_methods
        ]
    else:
        differences.append("- 未发现实现层面的偏差。")
    differences += ["", "**三、论文没有写清、无法比对的项**"]
    if unknown_methods:
        differences += [
            f"- {_ITEM_LABELS.get(c.item.value, c.item.value)}："
            f"本次实现为 {c.implementation_value}；{c.note}"
            for c in unknown_methods
        ]
    else:
        differences.append("- 无")
    sections.append("\n".join(differences))

    # --- 6. 风险 -------------------------------------------------------------
    auto_assumptions = [a for a in report.assumptions if a.confirmed_by is ConfirmationSource.AUTO]
    risks = ["## 6. 需要留意的地方", ""]
    risks.append(
        f"- **审核强度**：本次是「{_REVIEW_LABELS.get(mode, '审核来源未知')}」。"
        + (
            "关键假设由系统自动接受，没有人逐项看过，结果只能当趋势参考。"
            if auto_assumptions or mode == "delegated"
            else (report.review_disclaimer or "逐项确认来源见审核记录。")
        )
    )
    risks.append(
        f"- **假设数量**：共 {len(report.assumptions)} 项假设不是论文原文，"
        f"其中 {len(auto_assumptions)} 项由系统自动接受。假设越多，结论的不确定性越大。"
    )
    risks.append(
        "- **重复次数**：本次只跑了 1 个随机种子、1 次，没有置信区间。"
        "要判断稳定性，至少需要 3 个种子取平均。"
    )
    if report.missing_information:
        entries = [
            (item, _missing_text(item), _missing_gloss(item))
            for item in report.missing_information
        ]
        lines_out = [
            f"- **论文缺失信息 {len(entries)} 项**，这些空缺会用第 13 节的假设补上："
        ]
        for _raw, plain, gloss in entries[:8]:
            lines_out.append(f"  - {plain} —— {gloss}")
        if len(entries) > 8:
            lines_out.append(f"  - 另有 {len(entries) - 8} 项同类缺失，见第 13 节的假设记录。")
        risks.append("\n".join(lines_out))
    if report.limitations:
        risks.append(
            "- **这份报告的局限**："
            + "；".join(limitation.rstrip("；。") for limitation in report.limitations)
            + "。"
        )
    sections.append("\n".join(risks))

    # --- 7. 结论 -------------------------------------------------------------
    verdict = [
        "## 7. 结论",
        "",
        f"**判定：{_STATUS_LABELS[status]}**（{status.value}）",
        "",
        _STATUS_PLAIN[status],
        "",
        report.summary,
        "",
        "**建议的下一步**",
    ]
    if _is_random_guess(request, comparison):
        verdict += [
            "- 检查训练损失曲线和参数更新记录，了解训练过程。",
            "- 用多个随机种子和更大的测试集复测，观察准确率的波动。",
        ]
    elif status in (FinalStatus.METHOD_VALIDATED, FinalStatus.SCALED_RUN_COMPLETED):
        verdict += [
            "- 用 3 个随机种子重跑，给出均值与波动范围。",
            "- 逐步恢复论文的训练规模（样本量、轮数），观察指标是否向论文靠拢。",
        ]
    elif status is FinalStatus.EXECUTION_FAILED:
        verdict += ["- 查看第 11 节的退出码与错误信息，修复后重跑。"]
    else:
        verdict += [
            "- 先处理第 5 节中“实现与论文不一致”的项，再讨论数值差距。",
            "- 补充第 6 节列出的缺失信息后重新生成报告。",
        ]
    sections.append("\n".join(verdict))

    # --- 8. 证据基础 ---------------------------------------------------------
    method_rows = []
    for field, label in (
        (card.method, "方法"),
        (card.model_architecture, "架构"),
        (card.optimizer, "优化器"),
        (card.loss_function, "损失函数"),
        (card.dataset, "数据集"),
    ):
        method_rows.append(
            [
                label,
                field.value,
                _EVIDENCE_PLAIN.get(field.status.value, field.status.value),
                f"p.{field.source_page}" if field.source_page else "—",
                field.evidence_quote,
            ]
        )
    sections.append(
        "## 8. 论文信息与证据基础\n\n"
        + _table(
            ["字段", "内容"],
            [
                ["论文 ID", refs.paper_id],
                ["标题", title],
                ["方法", card.method.value],
                ["架构", card.model_architecture.value],
                ["数据集", card.dataset.value],
                ["卡片版本", f"v{refs.spec_version}（{refs.spec_version_id}）"],
            ],
        )
        + "\n\n每条关键信息的出处（页码与原文引文，`paper_explicit` 表示论文明确写了）：\n\n"
        + _table(["项", "值", "证据类型", "页码", "原文引文"], method_rows)
    )

    # --- 9. 完整配置 ---------------------------------------------------------
    def src(field) -> str:
        return _SOURCE_PLAIN.get(field.source.value, field.source.value)

    tc = plan.training_config
    full_setup_rows = [
        ["训练样本数", plan.dataset_config.train_subset_size, "计划设定（已缩小）"],
        ["测试样本数", plan.dataset_config.test_subset_size, "计划设定"],
        [
            "全量规模（训练/测试）",
            f"{plan.dataset_config.full_train_size}/{plan.dataset_config.full_test_size}",
            "数据集标准规模",
        ],
        ["训练轮数", tc.epochs.value, src(tc.epochs)],
        ["批大小", tc.batch_size.value, src(tc.batch_size)],
        ["优化器", tc.optimizer.value, src(tc.optimizer)],
        ["学习率", tc.learning_rate.value, src(tc.learning_rate)],
        ["损失函数", tc.loss_function.value, src(tc.loss_function)],
        ["随机种子", tc.seed, "固定值（保证能重跑）"],
    ]
    sections.append(
        "## 9. 完整训练配置与来源\n\n"
        "「来源」一列说明这个值是论文写的、系统推测的，还是为了跑得动而改的。\n\n"
        + _table(["参数", "计划取值", "来源"], full_setup_rows)
    )

    # --- 10. 代码 ------------------------------------------------------------
    conv_summary = ", ".join(
        f"卷积 {c.in_channels}→{c.out_channels}（核 {c.kernel_size}，填充 {c.padding}）"
        for c in facts.conv_layers
    )
    linear_summary = ", ".join(
        f"全连接 {layer.in_features}→{layer.out_features}" for layer in facts.linear_layers
    )
    pool_summary = ", ".join(f"{p.kind} 池化 核{p.kernel_size}/步{p.stride}" for p in facts.pooling)
    sections.append(
        "## 10. 代码实现明细\n\n"
        f"以下内容由本次运行固定的代码版本 v{refs.code_version} 静态解析得出，不是人工描述：\n\n"
        f"- 卷积层：{conv_summary or '—'}\n"
        f"- 池化：{pool_summary or '—'}\n"
        f"- 全连接层：{linear_summary or '—'}\n"
        f"- 激活函数：{', '.join(sorted(set(facts.activations))) or '—'}\n"
        f"- 损失函数：{facts.loss_function or '—'}\n"
        f"- 预处理：{', '.join(facts.preprocessing) or '—'}"
        + (
            f"（均值 {facts.normalize_mean}，标准差 {facts.normalize_std}）"
            if facts.normalize_mean is not None
            else ""
        )
        + "\n\n"
        + _table(["代码文件", "sha256"], [[f.path, f.sha256] for f in request.code_files])
    )

    # --- 11. 环境 ------------------------------------------------------------
    audit = request.audit
    sections.append(
        "## 11. 执行环境与审计\n\n"
        + _table(
            ["审计项", "值"],
            [
                ["镜像 digest", audit.image_digest if audit else None],
                ["Python 版本", audit.python_version if audit else None],
                ["依赖锁 hash", audit.dependency_lock_hash if audit else None],
                ["数据集指纹", audit.dataset_fingerprint if audit else None],
                ["随机种子", audit.seed if audit else None],
                ["代码 hash", audit.code_hash if audit else None],
                [
                    "执行时长",
                    f"{request.execution_time:.1f} 秒" if request.execution_time else None,
                ],
                ["退出码", request.exit_code],
            ],
        )
    )

    # --- 12. 逐项比对 --------------------------------------------------------
    sections.append(
        "## 12. 逐项比对明细\n\n"
        "**方法验证（论文写的 vs 代码实现的）**\n\n"
        + _table(
            ["项", "结论", "论文值", "实现值", "说明"],
            [
                [_ITEM_LABELS.get(c.item.value, c.item.value),
                 _CHECK_PLAIN.get(c.status.value, c.status.value),
                 c.paper_value, c.implementation_value, c.note]
                for c in report.method_checks
            ],
        )
        + "\n\n**实验验证（计划要跑的 vs 实际跑的）**\n\n"
        + _table(
            ["项", "结论", "计划值", "实际值", "说明"],
            [
                [_ITEM_LABELS.get(c.item.value, c.item.value),
                 _CHECK_PLAIN.get(c.status.value, c.status.value),
                 c.plan_value, c.actual_value, c.note]
                for c in report.experiment_checks
            ],
        )
    )

    # --- 13. 假设 ------------------------------------------------------------
    assumption_rows = [
        [_FIELD_LABELS.get(a.field_path.split(".")[-1], a.field_path), a.kind.value, a.value,
         a.rationale, _source_label(a.confirmed_by, a.human_confirmed)]
        for a in report.assumptions
    ]
    sections.append(
        "## 13. 假设与确认记录\n\n"
        "论文没写、由系统补上的取值。最后一列说明它是人工确认、AI 建议后采纳，"
        "还是系统自动接受：\n\n"
        + (
            _table(
                ["字段", "类型", "取值", "为什么这样取", "确认来源（非论文证据）"],
                assumption_rows,
            )
           if assumption_rows else "（本次没有产生假设）")
    )

    # --- 14. 追溯 ------------------------------------------------------------
    sections.append(
        "## 14. 追溯信息与审核记录\n\n"
        + _table(
            ["引用", "值"],
            [
                ["论文 ID", refs.paper_id],
                ["卡片版本 ID", f"{refs.spec_version_id}（v{refs.spec_version}）"],
                ["实验 ID", refs.experiment_id],
                ["计划 ID", f"{refs.plan_id}（v{refs.plan_version}）"],
                ["代码版本", f"v{refs.code_version}"],
                ["代码 hash", refs.code_hash],
                ["运行 ID", refs.run_id],
                ["运行状态", request.run_status.value],
                ["标准输出存档", request.stdout_path],
                ["错误输出存档", request.stderr_path],
                ["产物", ", ".join(request.artifacts) if request.artifacts else "—"],
            ],
        )
        + "\n\n固定代码文件 ID：\n"
        + (
            "\n".join(f"- `{fid}`" for fid in refs.generated_file_ids)
            if refs.generated_file_ids
            else "（无）"
        )
        + (
            f"\n\n失败信息：`{request.error_category.value if request.error_category else '—'}`"
            f" — {request.error}"
            if request.error
            else ""
        )
    )

    sections.append(
        "**审核 Trace 引用**\n\n"
        + (
            "\n".join(f"- [{tid}](#review-{tid})" for tid in refs.review_trace_ids)
            if refs.review_trace_ids else "（无持久审核事件；旧记录来源未知）"
        )
    )
    for decision in report.review_decisions:
        sections.append(
            f'<a id="review-{decision.id}"></a>\n\n'
            f"#### 审核事件 `{decision.id}`\n\n"
            + _table(["字段", "记录（已脱敏）"], [
                ["field", decision.field_path],
                ["old", _event_value(decision.before)],
                ["new", _event_value(decision.after)],
                ["source", _source_label(decision.confirmed_by)],
                ["review_mode", decision.review_mode],
                ["actor", decision.actor],
                ["time", decision.timestamp.isoformat()],
                ["recommendation_id", decision.recommendation_id],
                ["recommendation_confidence", decision.recommendation_confidence],
                ["recommendation_reasoning", decision.recommendation_reasoning],
                ["recommendation_risk", decision.recommendation_risk],
                ["preselection_threshold", decision.preselection_threshold],
            ])
        )

    return "\n\n".join(sections) + "\n"
