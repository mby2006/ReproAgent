"""Deterministic Markdown renderer for the reproduction report.

Layout is deliberately narrative-first: a reader who only knows the paper topic
should be able to stop after the summary block and still know what was run,
what came out, and whether the number can be trusted. Technical detail keeps
its original fields but moves behind the numbered appendix sections.

Every number is taken from the structured EvaluationReport / EvaluateRequest;
nothing is generated by an LLM. Tables escape pipes so evidence quotes cannot
break the layout.
"""

