"""Deterministic Markdown renderer for the 14-section reproduction report.

Every number is taken from the structured EvaluationReport / EvaluateRequest;
nothing is generated by an LLM. Tables escape pipes so evidence quotes cannot
break the layout.
"""

import json

from reproagent_schemas import EvaluateRequest, EvaluationReport, FinalStatus
from reproagent_schemas.common import ConfirmationSource

from .facts import ImplementationFacts

_STATUS_LABELS = {
    FinalStatus.METHOD_VALIDATED: "方法已验证（缩放运行）",
    FinalStatus.SCALED_RUN_COMPLETED: "缩放运行已完成",
    FinalStatus.PARTIAL_MATCH: "部分匹配",
    FinalStatus.DEVIATION_FOUND: "发现偏差",
    FinalStatus.INSUFFICIENT_EVIDENCE: "证据不足",
    FinalStatus.EXECUTION_FAILED: "执行失败",
}


_REVIEW_LABELS = {
    "expert": "人工逐项核验", "assisted": "AI 辅助审核", "delegated": "托管自动（未逐项核验）",
}
_SOURCE_LABELS = {
    ConfirmationSource.HUMAN: "human（人工确认）",
    ConfirmationSource.AI_ASSISTED: "ai_assisted（AI 辅助，人工采纳）",
    ConfirmationSource.AUTO: "auto（系统自动接受，非人工确认）",
}


def _source_label(source, human_confirmed: bool = False) -> str:
    return _SOURCE_LABELS.get(
        source, "unknown（旧记录已确认，来源未知）" if human_confirmed else "未确认"
    )


def _event_value(value: object) -> str:
    return json.dumps(value, ensure_ascii=False, sort_keys=True, default=str)


def _cell(value: object) -> str:
    if value is None:
        return "—"
    return str(value).replace("|", "\\|").replace("\n", " ")


def _table(headers: list[str], rows: list[list[object]]) -> str:
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join(["---"] * len(headers)) + "|"]
    for row in rows:
        lines.append("| " + " | ".join(_cell(v) for v in row) + " |")
    return "\n".join(lines)


def _fmt(value: float | None, digits: int = 4) -> str:
    return "—" if value is None else f"{value:.{digits}f}"


def render_markdown(
    request: EvaluateRequest, report: EvaluationReport, facts: ImplementationFacts
) -> str:
    card = request.card
    plan = request.plan
    refs = report.references
    sections: list[str] = []

    title = request.paper_title or str(card.method.value or "未命名论文")
    sections.append(
        f"# 复现报告：{title}\n\n"
        f"> 最终状态：**{report.final_status.value}**（{_STATUS_LABELS[report.final_status]}）\n>\n"
        f"> {report.summary}"
    )

    mode = report.review_mode.value if report.review_mode else "unknown"
    sections.append(
        f"> 审核模式：**{_REVIEW_LABELS.get(mode, '审核来源未知')} [{mode}]**\n>\n"
        f"> **{report.review_disclaimer or '缺少审核记录，不能认定已人工逐项核验。'}**"
        + (
            f"\n>\n> 托管授权用户：`{report.delegated_by}`；"
            f"授权时间：{report.delegated_at.isoformat()}"
            if report.delegated_at and report.delegated_by else ""
        )
    )

    sections.append(
        "## 1. Paper Overview\n\n"
        + _table(
            ["字段", "内容"],
            [
                ["Paper ID", refs.paper_id],
                ["标题", title],
                ["方法", card.method.value],
                ["架构", card.model_architecture.value],
                ["数据集", card.dataset.value],
                ["Spec 版本", f"v{refs.spec_version}（{refs.spec_version_id}）"],
            ],
        )
    )

    ev = plan.evaluation_config
    sections.append(
        "## 2. Reproduction Objective\n\n"
        f"{plan.rationale}\n\n"
        f"- 目标指标：`{ev.target_metric}`\n"
        f"- 计划记录参考值（不等于论文原文证据）：{_fmt(ev.reported_value)}"
        + (f"（{ev.reported_condition}）" if ev.reported_condition else "")
        + (f"，证据页 p.{ev.reported_source_page}" if ev.reported_source_page else "")
        + "\n"
        f"- 趋势容差：{ev.tolerance}\n"
        f"- 对比说明：{ev.comparison_note}"
    )

    method_rows = []
    for field, label in (
        (card.method, "方法"),
        (card.model_architecture, "架构"),
        (card.optimizer, "优化器"),
        (card.loss_function, "损失函数"),
        (card.dataset, "数据集"),
    ):
        method_rows.append(
            [
                label,
                field.value,
                field.status.value,
                f"p.{field.source_page}" if field.source_page else "—",
                field.evidence_quote,
            ]
        )
    sections.append(
        "## 3. Method Summary\n\n"
        + _table(["项", "值", "证据状态", "页码", "原文引文"], method_rows)
    )

    tc = plan.training_config
    setup_rows = [
        ["训练子集", plan.dataset_config.train_subset_size, "dataset_config.train_subset_size"],
        ["测试子集", plan.dataset_config.test_subset_size, "dataset_config.test_subset_size"],
        [
            "全量训练/测试",
            f"{plan.dataset_config.full_train_size}/{plan.dataset_config.full_test_size}",
            "MNIST 标准规模",
        ],
        ["Epochs", tc.epochs.value, f"training_config.epochs（{tc.epochs.source.value}）"],
        [
            "Batch size",
            tc.batch_size.value,
            f"training_config.batch_size（{tc.batch_size.source.value}）",
        ],
        ["优化器", tc.optimizer.value, f"training_config.optimizer（{tc.optimizer.source.value}）"],
        [
            "学习率",
            tc.learning_rate.value,
            f"training_config.learning_rate（{tc.learning_rate.source.value}）",
        ],
        [
            "损失函数",
            tc.loss_function.value,
            f"training_config.loss_function（{tc.loss_function.source.value}）",
        ],
        ["随机种子", tc.seed, "training_config.seed"],
    ]
    sections.append(
        "## 4. Experimental Setup\n\n" + _table(["参数", "计划值", "来源"], setup_rows)
    )

    deviation_rows = [
        [d.field_path, d.paper_value, d.plan_value, d.reason] for d in plan.deviations_from_paper
    ]
    sections.append(
        "## 5. Scaling Strategy\n\n"
        f"缩放 profile：`{plan.scaling_profile}`。以下配置**有意偏离原文**（MVP 缩放）：\n\n"
        + (
            _table(["字段", "原文值", "计划值", "原因"], deviation_rows)
            if deviation_rows
            else "（无记录的缩放偏差）"
        )
    )

    file_rows = [[f.path, f.sha256] for f in request.code_files]
    conv_summary = ", ".join(
        f"conv {c.in_channels}->{c.out_channels} (k{c.kernel_size}, p{c.padding})"
        for c in facts.conv_layers
    )
    linear_summary = ", ".join(
        f"linear {layer.in_features}->{layer.out_features}" for layer in facts.linear_layers
    )
    pool_summary = ", ".join(f"{p.kind}pool k{p.kernel_size}/s{p.stride}" for p in facts.pooling)
    sections.append(
        "## 6. Implementation Details\n\n"
        f"实现事实从本次运行固定的代码版本 v{refs.code_version} AST 提取：\n\n"
        f"- 卷积层：{conv_summary or '—'}\n"
        f"- 池化：{pool_summary or '—'}\n"
        f"- 全连接层：{linear_summary or '—'}\n"
        f"- 激活：{', '.join(sorted(set(facts.activations))) or '—'}\n"
        f"- 损失：{facts.loss_function or '—'}\n"
        f"- 预处理：{', '.join(facts.preprocessing) or '—'}"
        + (
            f"（mean={facts.normalize_mean}, std={facts.normalize_std}）"
            if facts.normalize_mean is not None
            else ""
        )
        + "\n\n"
        + _table(["代码文件", "sha256"], file_rows)
        + "\n\n### 方法验证明细\n\n"
        + _table(
            ["项", "状态", "论文值", "实现值", "说明"],
            [
                [c.item.value, c.status.value, c.paper_value, c.implementation_value, c.note]
                for c in report.method_checks
            ],
        )
    )

    audit = request.audit
    audit_rows = [
        ["镜像 digest", audit.image_digest if audit else None],
        ["Python 版本", audit.python_version if audit else None],
        ["依赖锁 hash", audit.dependency_lock_hash if audit else None],
        ["数据集指纹", audit.dataset_fingerprint if audit else None],
        ["随机种子", audit.seed if audit else None],
        ["代码 hash", audit.code_hash if audit else None],
        ["执行时长 (s)", request.execution_time],
        ["Exit code", request.exit_code],
    ]
    sections.append(
        "## 7. Execution Environment\n\n"
        + _table(["审计项", "值"], audit_rows)
        + "\n\n### 实验验证明细（计划 vs 实际）\n\n"
        + _table(
            ["项", "状态", "计划值", "实际值", "说明"],
            [
                [c.item.value, c.status.value, c.plan_value, c.actual_value, c.note]
                for c in report.experiment_checks
            ],
        )
    )

    comparison_rows = [
        [
            c.metric,
            _fmt(c.paper_value),
            _fmt(c.experiment_value),
            _fmt(c.absolute_difference),
            _fmt(c.relative_difference),
            (
                _fmt(c.percentage_point_difference, 2)
                if c.percentage_point_difference is not None
                else "—"
            ),
            c.unit,
            c.comparison_status.value,
        ]
        for c in report.metric_comparisons
    ]
    sections.append(
        "## 8. Results Comparison\n\n"
        + _table(
            ["指标", "论文值", "实验值", "绝对差", "相对差", "百分点差", "单位", "状态"],
            comparison_rows,
        )
        + "\n\n所有实验值来自真实运行 metrics.json；所有论文值来自证据落地的 Card "
        "reported_results。tolerance 仅作趋势参考，**数值接近不等于完整复现**。"
    )

    method_deviations = [c for c in report.method_checks if c.status.value == "deviated"]
    sections.append(
        "## 9. Method Deviations\n\n"
        + (
            _table(
                ["项", "论文值", "实现值", "说明"],
                [
                    [c.item.value, c.paper_value, c.implementation_value, c.note]
                    for c in method_deviations
                ],
            )
            if method_deviations
            else "方法验证未发现与论文证据冲突的实现偏差。"
        )
        + "\n\n缩放偏差（有意为之，见第 5 节）：\n"
        + (
            "\n".join(
                f"- `{d.field_path}`：{d.paper_value} → {d.plan_value}（{d.reason}）"
                for d in plan.deviations_from_paper
            )
            if plan.deviations_from_paper
            else "（无）"
        )
    )

    missing = list(report.missing_information)
    sections.append(
        "## 10. Missing Information\n\n"
        + ("\n".join(f"- {m}" for m in missing) if missing else "（无记录的缺失信息）")
    )

    assumption_rows = [
        [a.field_path, a.kind.value, a.value, a.rationale,
         _source_label(a.confirmed_by, a.human_confirmed)]
        for a in report.assumptions
    ]
    sections.append(
        "## 11. Agent Assumptions\n\n"
        + (
            _table(["字段", "类型", "值", "理由", "确认来源（非论文证据）"], assumption_rows)
            if assumption_rows
            else "（无假设）"
        )
    )

    sections.append(
        "## 12. Known Limitations\n\n"
        + "\n".join(f"- {limitation}" for limitation in report.limitations)
    )

    sections.append(
        "## 13. Final Assessment\n\n"
        f"**{report.final_status.value}** — {_STATUS_LABELS[report.final_status]}\n\n"
        f"{report.summary}"
    )

    trace_rows = [
        ["Paper ID", refs.paper_id],
        ["Spec Version ID", f"{refs.spec_version_id}（v{refs.spec_version}）"],
        ["Experiment ID", refs.experiment_id],
        ["Plan ID", f"{refs.plan_id}（v{refs.plan_version}）"],
        ["Code Version", f"v{refs.code_version}"],
        ["Code Hash", refs.code_hash],
        ["Execution Run ID", refs.run_id],
        ["运行状态", request.run_status.value],
        ["stdout 存储路径", request.stdout_path],
        ["stderr 存储路径", request.stderr_path],
        ["产物", ", ".join(request.artifacts) if request.artifacts else "—"],
    ]
    sections.append(
        "## 14. Code and Execution Trace References\n\n"
        + _table(["引用", "值"], trace_rows)
        + "\n\n固定代码文件 ID：\n"
        + (
            "\n".join(f"- `{fid}`" for fid in refs.generated_file_ids)
            if refs.generated_file_ids
            else "（无）"
        )
        + (
            f"\n\n失败信息：`{request.error_category.value if request.error_category else '—'}`"
            f" — {request.error}"
            if request.error
            else ""
        )
    )

    sections.append(
        "### 审核 Trace 引用\n\n"
        + (
            "\n".join(f"- [{tid}](#review-{tid})" for tid in refs.review_trace_ids)
            if refs.review_trace_ids else "（无持久审核事件；旧记录来源未知）"
        )
    )
    for decision in report.review_decisions:
        sections.append(
            f'<a id="review-{decision.id}"></a>\n\n'
            f"#### 审核事件 `{decision.id}`\n\n"
            + _table(["字段", "记录（已脱敏）"], [
                ["field", decision.field_path],
                ["old", _event_value(decision.before)],
                ["new", _event_value(decision.after)],
                ["source", _source_label(decision.confirmed_by)],
                ["review_mode", decision.review_mode],
                ["actor", decision.actor],
                ["time", decision.timestamp.isoformat()],
                ["recommendation_id", decision.recommendation_id],
                ["recommendation_confidence", decision.recommendation_confidence],
                ["recommendation_reasoning", decision.recommendation_reasoning],
                ["recommendation_risk", decision.recommendation_risk],
                ["preselection_threshold", decision.preselection_threshold],
            ])
        )

    return "\n\n".join(sections) + "\n"